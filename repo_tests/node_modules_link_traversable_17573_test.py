"""A linked `node_modules` must be usable, not merely present (#17573).

#16912 gave every worktree a frontend toolchain by symlinking the main
checkout's install, and `scripts/hooks/post-checkout` prints

    🔗 Linked <project>/node_modules -> the main checkout's install (#16912)

The gate behind that line was `[ -d "$_src" ]`. A directory carrying no execute
bit answers `-d` **yes** and denies everything inside it, so on a host where
`autobot-slm-frontend/node_modules` is mode 644 — measured, and reproduced from
the main checkout by three sessions — the link resolved, the line said "Linked",
and every binary under `.bin` was unreachable:

    $ npm run type-check      ->  sh: 1: vue-tsc: Permission denied
    $ ls node_modules/.bin/vue-tsc  ->  Permission denied

So #16912's remedy was in place and inert for that tree, and the hook reported
success for a target it never entered. That is the same shape as this repository's
recurring defect: a check that cannot fail, reporting the thing it did not do.

The hook cannot fix a mode it does not own — the directory belongs to the main
checkout and is shared by every worktree, so three sessions independently
declined to `chmod` it. What it can do is refuse to claim success, and say what
is broken and where.

These tests drive the real hook in a throwaway repository with a real linked
worktree, the way `hook_self_sync_atomic_test.py` does, because the behaviour
under test is a mode bit's effect on `ln` and a `[ -x ]` test — nothing a source
grep can see.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest
from repo_tests._paths import repo_root

from autobot_shared.paths import scrubbed_git_env

REPO_ROOT = repo_root()
_HOOK = REPO_ROOT / "scripts" / "hooks" / "post-checkout"

#: The two projects the link step knows about.
_GOOD = "autobot-frontend"
_BAD = "autobot-slm-frontend"

pytestmark = pytest.mark.skipif(
    os.geteuid() == 0,
    reason="root ignores the mode bits, so every assertion here would pass for the wrong reason",
)


def _git(cwd: Path, *args: str) -> subprocess.CompletedProcess:
    """#15246: env scrubbed, or an inherited GIT_DIR aims these at the real repo."""
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False, env=scrubbed_git_env())


def _seed(tmp_path: Path) -> tuple[Path, Path]:
    """A main checkout with both frontends, and the real hook installed.

    Returns `(main, hooks_dir)`. The install directories are created untracked,
    exactly as a real `npm ci` leaves them.
    """
    main = tmp_path / "main"
    for project in (_GOOD, _BAD):
        (main / project).mkdir(parents=True)
        (main / project / "package.json").write_text("{}\n", encoding="utf-8")
    (main / "scripts" / "hooks").mkdir(parents=True)

    _git(tmp_path, "init", "--quiet", "--initial-branch=main", str(main))
    _git(main, "config", "user.email", "t@t")
    _git(main, "config", "user.name", "t")
    hook = main / "scripts" / "hooks" / "post-checkout"
    hook.write_text(_HOOK.read_text(encoding="utf-8"), encoding="utf-8")
    hook.chmod(0o755)
    _git(main, "add", "-A")
    _git(main, "commit", "--quiet", "-m", "seed")

    hooks_dir = main / ".git" / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    live = hooks_dir / "post-checkout"
    live.write_text(hook.read_text(encoding="utf-8"), encoding="utf-8")
    live.chmod(0o755)

    # Both installs present. Only one of them is traversable.
    (main / _GOOD / "node_modules").mkdir(mode=0o755)
    (main / _BAD / "node_modules").mkdir(mode=0o755)
    return main, hooks_dir


def _add_worktree(main: Path, tmp_path: Path) -> tuple[Path, str]:
    """Create a linked worktree, which is what fires the link step."""
    worktree = tmp_path / "wt"
    completed = _git(main, "worktree", "add", "--quiet", "-b", "other", str(worktree))
    return worktree, completed.stdout + completed.stderr


class TestAnUnusableInstallIsNotReportedAsLinked:
    """The mode-644 case, which `-d` cannot see."""

    def test_the_untraversable_project_is_not_claimed_as_linked(self, tmp_path: Path) -> None:
        main, _ = _seed(tmp_path)
        install = main / _BAD / "node_modules"
        install.chmod(0o644)
        try:
            worktree, output = _add_worktree(main, tmp_path)
        finally:
            install.chmod(0o755)

        assert f"Linked {_BAD}" not in output, output
        assert not (worktree / _BAD / "node_modules").exists()

    def test_it_says_what_is_wrong_and_where(self, tmp_path: Path) -> None:
        """A silent skip is the failure mode #16912 removed one branch over.

        This hook is the only place that knows why local verification will not
        work for that project, so it is the only place that can say so.
        """
        main, _ = _seed(tmp_path)
        install = main / _BAD / "node_modules"
        install.chmod(0o644)
        try:
            _, output = _add_worktree(main, tmp_path)
        finally:
            install.chmod(0o755)

        assert "cannot be traversed" in output
        assert _BAD in output
        assert "644" in output, f"the mode is the actionable part: {output}"
        assert "17573" in output

    def test_the_traversable_project_is_still_linked(self, tmp_path: Path) -> None:
        """The positive control. A check that refused both would pass the test
        above while removing the feature #16912 added."""
        main, _ = _seed(tmp_path)
        install = main / _BAD / "node_modules"
        install.chmod(0o644)
        try:
            worktree, output = _add_worktree(main, tmp_path)
        finally:
            install.chmod(0o755)

        assert f"Linked {_GOOD}" in output, output
        link = worktree / _GOOD / "node_modules"
        assert link.is_symlink()
        assert link.resolve() == (main / _GOOD / "node_modules").resolve()


class TestTheHappyPathIsUnchanged:
    """#16912's behaviour when both installs are fine."""

    def test_both_projects_are_linked(self, tmp_path: Path) -> None:
        main, _ = _seed(tmp_path)

        worktree, output = _add_worktree(main, tmp_path)

        for project in (_GOOD, _BAD):
            assert f"Linked {project}" in output, output
            assert (worktree / project / "node_modules").is_symlink()

    def test_no_traversability_warning_when_nothing_is_wrong(self, tmp_path: Path) -> None:
        """The warning must not become background noise on a healthy checkout."""
        main, _ = _seed(tmp_path)

        _, output = _add_worktree(main, tmp_path)

        assert "cannot be traversed" not in output

    def test_a_missing_install_is_still_just_skipped(self, tmp_path: Path) -> None:
        """Absent is not the same as unusable, and only one of them is a defect.

        A main checkout that never ran `npm ci` for a project is an ordinary
        state, so it gets no warning and no link.
        """
        main, _ = _seed(tmp_path)
        (main / _BAD / "node_modules").rmdir()

        worktree, output = _add_worktree(main, tmp_path)

        assert "cannot be traversed" not in output
        assert f"Linked {_BAD}" not in output
        assert not (worktree / _BAD / "node_modules").exists()
