"""Which guard test to run when a path under its declared ``roots=`` changes (#18808).

tools/lint/prepush_selection.py reads REACH_ROOTS (repo_tests/_reach_roots_record.py) as data:
the hook must not import repo_tests. A ``roots=`` written as a module constant, an import or a
comprehension is invisible to a parse of the ``declare(`` call, which saw 31 of 90 sites, so
the record is computed from the live registry here and pinned by
repo_tests/reach_roots_record_18808_test.py. Regenerate it with
``python -m repo_tests._reach_roots``.
"""

from __future__ import annotations

import sys
from pathlib import Path

from repo_tests._paths import repo_root

_ROOT = repo_root()
_PATTERNS = ("test_", "_test.py")


def _is_test(rel: str) -> bool:
    name = rel.rsplit("/", 1)[-1]
    return name.startswith(_PATTERNS[0]) or name.endswith(_PATTERNS[1])


def _importers(module: str) -> list[str]:
    """Test files under repo_tests that import *module* (a helper that declares for them)."""
    needles = (f"from {module} import", f"import {module}")
    return sorted(
        f"repo_tests/{p.name}"
        for p in (_ROOT / "repo_tests").glob("*_test.py")
        if any(n in p.read_text(encoding="utf-8", errors="replace") for n in needles)
    )


def expected_record() -> dict[str, tuple[str, ...]]:
    """``{test file: roots}`` for every live declaration that carries ``roots=``."""
    from repo_tests._guard_import import import_every_guard  # noqa: PLC0415
    from repo_tests._reach import REGISTRY  # noqa: PLC0415

    import_every_guard()

    record: dict[str, set[str]] = {}
    for name, reach in REGISTRY.items():
        if not reach.roots or name.startswith("self-check::"):
            continue
        module = getattr(reach.discover, "__module__", "")
        path = getattr(sys.modules.get(module), "__file__", None)
        if not path:
            continue
        rel = Path(path).resolve().relative_to(_ROOT).as_posix()
        for test in [rel] if _is_test(rel) else _importers(module):
            record.setdefault(test, set()).update(reach.roots)
    return {test: tuple(sorted(roots)) for test, roots in sorted(record.items())}


def render(record: dict[str, tuple[str, ...]]) -> str:
    """The record module's source."""
    body = "".join(f"    {test!r}: {roots!r},\n" for test, roots in record.items())
    return (
        "# Copyright 2025-2026 mrveiss\n# SPDX-License-Identifier: Apache-2.0\n"
        '"""Generated by ``python -m repo_tests._reach_roots`` -- do not edit by hand (#18808)."""\n\n'
        "REACH_ROOTS = {\n" + body + "}\n"
    )


RECORD = _ROOT / "repo_tests" / "_reach_roots_record.py"

if __name__ == "__main__":
    # Written directly, not to stdout: importing the guards logs to stdout.
    RECORD.write_text(render(expected_record()), encoding="utf-8")
