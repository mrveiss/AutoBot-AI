"""Render the GitHub wiki from docs/ (#19278).

Owner decision 2026-10-23: the repo docs are the single source and the wiki is generated by CI,
never edited by hand. Each page in docs/wiki/manifest.yml maps to one source file; every
generated page opens with a header naming its source path and commit. Relative links are
rewritten to the repository at that commit, since they would break inside the wiki.

The API page is generated from the backend's OpenAPI paths (the generated frontend types), so
it lists only paths the backend serves. ``check_api_page`` is a SELF-CONSISTENCY check -- it
compares the page with the same path list it was rendered from, guarding the renderer, not the
source; the source's fidelity is the generated types' own CI check (verify-generated-types).

The wiki is public: private (RFC 1918) addresses and home-directory paths in a source are
redacted in the output, and ``scan_output`` fails the build if any survive. /opt/autobot and
/var/log/autobot are the documented install layout and are kept.

Usage: build_wiki.py OUT_DIR [--sha SHA]
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess  # nosec B404  # fixed argv, no shell
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from autobot_shared.paths import scrubbed_git_env  # noqa: E402 - after the repo root is importable

MANIFEST = ROOT / "docs" / "wiki" / "manifest.yml"
API_TYPES = ROOT / "autobot-frontend" / "src" / "types" / "generated" / "api.ts"
_API_PATH = re.compile(r'^    "(/api/[^"]*)": \{', re.MULTILINE)
_LINK = re.compile(r"(\]\()([^)\s#]+)(#[^)\s]*)?(\))")
_REF_DEF = re.compile(r"^(\s{0,3}\[[^\]]+\]:\s+)(\S+?)(#\S*)?(\s.*)?$", re.MULTILINE)
_FENCE = re.compile(r"^(```|~~~).*?^\1", re.MULTILINE | re.DOTALL)
# Lookarounds, not \b: an address glued to a word ("host10.0.0.1") has no word boundary before it.
_PRIVATE_IP = re.compile(r"(?<![\d.])(?:10\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01])|192\.168)\.\d{1,3}\.\d{1,3}(?![\d.])")
_HOME = re.compile(r"/home/[\w.-]+")


def repo_url() -> str:
    """The repository's web URL: from Actions' env in CI, else from the ``origin`` remote."""
    server, repo = os.environ.get("GITHUB_SERVER_URL"), os.environ.get("GITHUB_REPOSITORY")
    if server and repo:
        return f"{server}/{repo}"
    remote = subprocess.run(  # nosec B603 B607  # fixed argv, no shell
        ["git", "-C", str(ROOT), "remote", "get-url", "origin"],
        capture_output=True,
        text=True,
        check=True,
        env=scrubbed_git_env(),
    ).stdout.strip()
    remote = re.sub(r"^git@([^:]+):", r"https://\1/", remote)
    return remote.removesuffix(".git")


def api_paths(types_text: str) -> list[str]:
    """The backend's API paths, from the generated OpenAPI types."""
    return sorted(set(_API_PATH.findall(types_text)))


def header(source: str, sha: str, url: str) -> str:
    return (
        f"> **Generated** from [`{source}`]({url}/blob/{sha}/{source}) at `{sha[:12]}`. "
        "Edit the source, not this page -- the next merge to main overwrites any change here.\n\n"
    )


def _resolve(target: str, base: Path, sha: str, url: str) -> str | None:
    """*target* as a repository URL at *sha*, or None when it is absolute, a scheme, or root-relative."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.IGNORECASE) or target.startswith("/"):
        return None
    parts = [p for p in (base / target).as_posix().split("/") if p not in ("", ".")]
    while ".." in parts:
        i = parts.index("..")
        parts[max(0, i - 1) : i + 1] = []
    return f"{url}/blob/{sha}/{'/'.join(parts)}"


def rewrite_links(markdown: str, source: str, sha: str, url: str) -> str:
    """Point relative links -- inline and reference-style -- at the repository at *sha*.
    Absolute, anchor and root links are kept, and fenced code is left untouched."""
    base = Path(source).parent

    def inline(m: re.Match) -> str:
        new = _resolve(m.group(2), base, sha, url)
        return m.group(0) if new is None else f"{m.group(1)}{new}{m.group(3) or ''}{m.group(4)}"

    def ref(m: re.Match) -> str:
        new = _resolve(m.group(2), base, sha, url)
        return m.group(0) if new is None else f"{m.group(1)}{new}{m.group(3) or ''}{m.group(4) or ''}"

    out, last = [], 0
    for fence in _FENCE.finditer(markdown):
        prose = markdown[last : fence.start()]
        out.append(_REF_DEF.sub(ref, _LINK.sub(inline, prose)))
        out.append(fence.group(0))
        last = fence.end()
    out.append(_REF_DEF.sub(ref, _LINK.sub(inline, markdown[last:])))
    return "".join(out)


def redact(text: str) -> str:
    """Private addresses and home paths out: the wiki is public."""
    return _HOME.sub("<home>", _PRIVATE_IP.sub("<private-ip>", text))


def scan_output(name: str, text: str) -> list[str]:
    """Anything internal that survived redaction -- must be empty."""
    return [f"{name}: {m}" for m in _PRIVATE_IP.findall(text) + _HOME.findall(text)]


def render_api(paths: list[str], sha: str, url: str) -> str:
    """The API page: every path the backend serves, grouped by its first segment."""
    groups: dict[str, list[str]] = {}
    for path in paths:
        groups.setdefault(path.split("/")[2] if path.count("/") > 1 else "", []).append(path)
    body = [
        header("autobot-frontend/src/types/generated/api.ts", sha, url),
        "# API\n",
        f"{len(paths)} paths, generated from the backend's OpenAPI schema.\n",
    ]
    for group in sorted(groups):
        body.append(f"\n## /api/{group}\n\n" + "\n".join(f"- `{p}`" for p in groups[group]) + "\n")
    return "".join(body)


def check_api_page(page: str, paths: list[str]) -> list[str]:
    """API paths named on the page that the backend does not serve -- must be empty."""
    known = set(paths)
    return sorted({p for p in re.findall(r"`(/api/[^`]*)`", page) if p not in known})


def build(out: Path, sha: str, url: str) -> list[str]:
    """Write every manifest page into *out*; returns the page names written."""
    pages = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))["pages"]
    out.mkdir(parents=True, exist_ok=True)
    paths = api_paths(API_TYPES.read_text(encoding="utf-8"))
    for name, source in pages.items():
        if source == "api":
            text = render_api(paths, sha, url)
            stray = check_api_page(text, paths)
            if stray:
                raise SystemExit(f"API page names paths the backend does not serve: {stray[:5]}")
        else:
            text = header(source, sha, url) + rewrite_links(
                (ROOT / source).read_text(encoding="utf-8"), source, sha, url
            )
        text = redact(text)
        leaked = scan_output(name, text)
        if leaked:
            raise SystemExit(f"internal values would be published: {leaked[:5]}")
        (out / f"{name}.md").write_text(text, encoding="utf-8")
    return list(pages)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("out", type=Path)
    parser.add_argument("--sha", default=None)
    args = parser.parse_args(argv)
    sha = (
        args.sha
        or subprocess.run(  # nosec B603 B607  # fixed argv, no shell
            ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            env=scrubbed_git_env(),
        ).stdout.strip()
    )
    written = build(args.out, sha, repo_url())
    print(f"wrote {len(written)} wiki pages to {args.out}: {', '.join(written)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
