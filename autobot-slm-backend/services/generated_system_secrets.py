"""Seed SLM-generated service secrets into ``SystemSecret`` once, at startup.

Three service credentials are generated by the SLM rather than typed in by an
admin: the shared internal API key (#10263), the SCIM bearer token (#10157) and
the Prometheus scrape token (#16375). Each used to be -- or would have been --
its own copy of the same select / add / commit / IntegrityError block in
``main.py``; this is the one copy.

Idempotent: an existing row, operator-set or generated, is never overwritten,
and a concurrent startup that seeds the key first wins. A generated value never
appears in a log line or an exception message.

Vault mirror retry: for a ``mirror_to_vault`` secret, every startup whose row
already exists copies it to the System vault when the vault copy is missing
(``migrate_key_to_vault`` is idempotent). A mirror that failed because the
backend vault was down at first boot is therefore retried on each restart,
never left absent for good. Rotation is documented in
``docs/developer/THREAT_MODEL.md`` (Prometheus scrape token).
"""

from __future__ import annotations

import secrets
from dataclasses import dataclass

from autobot_shared.logging_manager import get_logger

logger = get_logger(__name__)


@dataclass(frozen=True)
class GeneratedSecret:
    """A ``SystemSecret`` key the SLM generates when absent."""

    key: str
    issue: str
    description: str | None = None
    #: Mirror to the System vault the way an admin-created secret is (#14759).
    #: Off for the auth-bootstrap key, which ``is_migratable`` refuses anyway.
    mirror_to_vault: bool = False


INTERNAL_API_KEY = GeneratedSecret(key="autobot_internal_api_key", issue="#10263")  # nosec B106  # key name
SCIM_BEARER_TOKEN = GeneratedSecret(  # nosec B106  # key name, not a credential
    key="scim_bearer_token",
    issue="#10157",
    description="SCIM 2.0 bearer token — configure in IdP SCIM provisioning settings (#10157)",
)
PROMETHEUS_SCRAPE_TOKEN = GeneratedSecret(  # nosec B106  # key name, not a credential
    key="prometheus_scrape_token",
    issue="#16375",
    description="Read-only bearer token Prometheus presents to the backend metrics endpoint (#16375)",
    mirror_to_vault=True,
)


async def _insert_if_absent(spec: GeneratedSecret, value: str) -> bool:
    """Add the row unless it exists; False when it already did (or a racer won)."""
    from sqlalchemy import select
    from sqlalchemy.exc import IntegrityError

    from models.database import SystemSecret
    from services.database import db_service
    from services.encryption import encrypt_data

    async with db_service.session() as db:
        found = await db.execute(select(SystemSecret).where(SystemSecret.key == spec.key))
        if found.scalar_one_or_none() is not None:
            return False
        db.add(SystemSecret(key=spec.key, encrypted_value=encrypt_data(value), description=spec.description))
        try:
            await db.commit()
        except IntegrityError:
            await db.rollback()
            logger.info("%s already seeded concurrently — keeping existing (%s)", spec.key, spec.issue)
            return False
    return True


async def _backfill_vault_copy(spec: GeneratedSecret) -> None:
    """Copy an existing row to the System vault when the vault copy is missing."""
    from services.database import db_service
    from services.system_secrets_vault import migrate_key_to_vault

    try:
        async with db_service.session() as db:
            await migrate_key_to_vault(db, spec.key)
    except Exception as exc:  # noqa: BLE001 — best-effort; the next startup retries
        logger.warning("%s vault mirror retry failed (%s); retried next startup", spec.key, type(exc).__name__)


async def ensure_generated_secret(spec: GeneratedSecret) -> None:
    """Generate *spec*'s secret once; never overwrite an existing value."""
    value = secrets.token_hex(32)
    if not await _insert_if_absent(spec, value):
        if spec.mirror_to_vault:
            await _backfill_vault_copy(spec)
        return
    if spec.mirror_to_vault:
        from services.system_secrets_vault import mirror_secret_to_vault

        await mirror_secret_to_vault(spec.key, value)
    logger.info("Generated system secret %s (%s)", spec.key, spec.issue)
